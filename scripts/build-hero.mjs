// Builds the CARMA hero and the favicon (original artwork, no third-party imagery):
//   src/components/hero-svg.ts   the landing-page hero as an inline SVG string (colours are CSS variables)
//   public/favicon.svg           the compact mark: a hub with five spokes
// The hero is a hub (the wordmark) with spokes to five highlighted assets and a fainter outer network.
// Spokes start on the wordmark's padded box, so no line crosses the letters. Run: node scripts/build-hero.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const W = 1200, H = 300;
const BOX = { x0: 418, x1: 782, y0: 104, y1: 196 }; // wordmark + padding
const C = { x: (BOX.x0 + BOX.x1) / 2, y: (BOX.y0 + BOX.y1) / 2 };
const hot = [[318, 86], [292, 222], [884, 64], [920, 214], [664, 268]];
const outer = [
  [60, 60], [150, 150], [96, 246], [210, 30], [214, 270], [420, 34], [430, 268], [520, 22], [790, 24], [800, 276],
  [1010, 40], [1050, 140], [1120, 70], [1004, 266], [1140, 236], [1180, 150], [30, 170], [560, 284], [960, 140], [240, 140],
];
const hotOuter = [[0, 3], [0, 19], [0, 5], [1, 4], [1, 1], [1, 19], [2, 8], [2, 10], [3, 18], [3, 13], [3, 9], [4, 17], [4, 9], [2, 18]];
const outerOuter = [[0, 3], [0, 16], [16, 1], [1, 2], [2, 4], [3, 5], [5, 7], [4, 6], [6, 17], [8, 10], [10, 12], [12, 15], [11, 15], [11, 18], [13, 14], [14, 15], [9, 13], [1, 19]];

// Where the line from the hub centre to p leaves the box.
function exitBox(p) {
  const dx = p[0] - C.x, dy = p[1] - C.y;
  const tx = dx ? ((dx > 0 ? BOX.x1 : BOX.x0) - C.x) / dx : Infinity;
  const ty = dy ? ((dy > 0 ? BOX.y1 : BOX.y0) - C.y) / dy : Infinity;
  const t = Math.min(Math.abs(tx), Math.abs(ty));
  return [C.x + dx * t, C.y + dy * t];
}
// Does segment p-q cross the box? (sampled; the box is large relative to the step)
const crossesBox = (p, q) => Array.from({ length: 41 }, (_, i) => i / 40).some((t) => {
  const x = p[0] + (q[0] - p[0]) * t, y = p[1] + (q[1] - p[1]) * t;
  return x > BOX.x0 && x < BOX.x1 && y > BOX.y0 && y < BOX.y1;
});
const f = (v) => +v.toFixed(1);
const line = (p, q, cls, extra = '') => `<line class="${cls}" x1="${f(p[0])}" y1="${f(p[1])}" x2="${f(q[0])}" y2="${f(q[1])}"${extra}/>`;

const parts = [];
parts.push('<defs><radialGradient id="carma-glow"><stop offset="0" stop-color="var(--hero-glow)" style="stop-opacity: var(--hero-glow-a)"/><stop offset="0.55" stop-color="var(--hero-glow)" style="stop-opacity: var(--hero-glow-b)"/><stop offset="1" stop-color="var(--hero-glow)" stop-opacity="0"/></radialGradient></defs>');
for (const [a, b] of outerOuter) if (!crossesBox(outer[a], outer[b])) parts.push(line(outer[a], outer[b], 'hero-edge-outer'));
for (const [h, o] of hotOuter) if (!crossesBox(hot[h], outer[o])) parts.push(line(hot[h], outer[o], 'hero-edge'));
parts.push(`<ellipse class="hero-glow" cx="${C.x}" cy="${C.y}" rx="250" ry="120" fill="url(#carma-glow)"/>`);
hot.forEach((p, i) => {
  const s = exitBox(p);
  parts.push(line(s, p, 'hero-spoke'));
  if (i !== 4) parts.push(line(s, p, 'hero-flow', ` style="animation-delay: ${(-i * 0.7).toFixed(1)}s"`));
});
for (const p of outer) parts.push(`<circle class="hero-node-outer" cx="${p[0]}" cy="${p[1]}" r="5"/>`);
hot.forEach((p, i) => parts.push(`<circle class="hero-node-ring" cx="${p[0]}" cy="${p[1]}" r="${i === 2 ? 15 : 12}"/><circle class="hero-node" cx="${p[0]}" cy="${p[1]}" r="${i === 2 ? 9 : 7}"/>`));
// Tag on the highlighted asset at the top right (16 units, so it stays at least 12 px when the hero is shown 920 px wide).
const T = hot[2];
parts.push(`<g class="hero-tag"><rect x="${T[0] + 20}" y="${T[1] - 15}" width="176" height="30" rx="15"/><text x="${T[0] + 108}" y="${T[1] + 6}" text-anchor="middle">Most Critical Asset</text></g>`);
parts.push(`<text class="hero-wordmark" x="${C.x}" y="${C.y + 29}" text-anchor="middle">CARMA</text>`);
const heroSvg = `<svg class="carma-hero" viewBox="0 0 ${W} ${H}" role="img" aria-label="CARMA: a network with one central hub and the assets its failure reaches">${parts.join('')}</svg>`;

fs.writeFileSync(path.join(root, 'src/components/hero-svg.ts'), [
  '// Generated by scripts/build-hero.mjs: do not edit by hand. Styles: .carma-hero in src/styles/base.css.',
  `export const HERO_SVG = ${JSON.stringify(heroSvg)};`,
  '',
].join('\n'));

// Favicon: the same hub-and-spokes symbol as the app bar (src/components/ui.tsx BrandMark), in fixed colours.
const spokes = Array.from({ length: 5 }, (_, i) => { const a = -Math.PI / 2 + i * 2 * Math.PI / 5; return [16 + Math.cos(a) * 12.5, 16 + Math.sin(a) * 12.5]; });
const favicon = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">'
  + '<style>.s{stroke:#D58E9B}.g{fill:rgba(226,50,79,.22)}.n{fill:#B4122F}@media (prefers-color-scheme: dark){.s{stroke:#B05566}.g{fill:rgba(255,45,74,.3)}.n{fill:#FF3A55}}</style>'
  + spokes.map(([x, y]) => `<line class="s" x1="16" y1="16" x2="${f(x)}" y2="${f(y)}" stroke-width="2.2" stroke-linecap="round"/>`).join('')
  + '<circle class="g" cx="16" cy="16" r="9"/>'
  + spokes.map(([x, y]) => `<circle class="n" cx="${f(x)}" cy="${f(y)}" r="3.1"/>`).join('')
  + '<circle class="n" cx="16" cy="16" r="5.6"/></svg>\n';
fs.writeFileSync(path.join(root, 'public/favicon.svg'), favicon);
console.log('hero', heroSvg.length, 'chars; spokes', JSON.stringify(spokes.map(([x, y]) => [f(x), f(y)])));
